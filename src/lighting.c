void bake_light_map()
{
    /**
     * foreach torch in light_map
     * do
     *     foreach neighboring cell
     *     do
     *         assign a lower float value
     *         if max depth is reached
     *         then
     *             stop
     *         endif
     *     end inner
     * end outer
     */

    for (int y = 0; y < ROWS; y++)
    {
        for (int x = 0; x < COLS; x++)
        {
            if (light_map[x][y] > 0)
            {
                printf("found light at %d, %d\n", y, x);

                // iterate over the neighboring cells
                // assing lower values for them
                // render these

                // north
                light_map[x][y - 1] = 0.5f;

                // south
                light_map[x][y + 1] = 0.5f;

                // east
                light_map[x - 1][y] = 0.5f;

                // west
                light_map[x + 1][y] = 0.5f;

                goto yeppers;
            }
        }
    }

yeppers:

    for (int y = 0; y < ROWS; y++)
    {
        for (int x = 0; x < COLS; x++)
        {
            printf("%.2f ", light_map[x][y]);
        }
        printf("\n");
    }
}